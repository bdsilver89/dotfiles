vim.keymap.set("n", "j", "v:count == 0 ? 'gj' : 'j'", { expr = true, silent = true })
vim.keymap.set("n", "<down>", "v:count == 0 ? 'gj' : 'j'", { expr = true, silent = true })
vim.keymap.set("n", "k", "v:count == 0 ? 'gk' : 'k'", { expr = true, silent = true })
vim.keymap.set("n", "<up>", "v:count == 0 ? 'gk' : 'k'", { expr = true, silent = true })

vim.keymap.set("n", "<c-d>", "<c-d>zz")
vim.keymap.set("n", "<c-u>", "<c-u>zz")
vim.keymap.set("n", "n", "nzzzv")
vim.keymap.set("n", "N", "nzzzv")

vim.keymap.set("n", "-", "<Plug>(nvim-dir-up)")

vim.keymap.set("n", "<esc>", function()
  local ns = vim.api.nvim_create_namespace("nvim.multicursor")
  vim.api.nvim_buf_clear_namespace(0, ns, 0, -1)
  vim.cmd.nohlsearch()
end)

vim.keymap.set("n", "<c-h>", "<c-w>h")
vim.keymap.set("n", "<c-j>", "<c-w>j")
vim.keymap.set("n", "<c-k>", "<c-w>k")
vim.keymap.set("n", "<c-l>", "<c-w>l")

vim.keymap.set("n", "<leader>-", "<c-w>s", { desc = "Split window horizontal" })
vim.keymap.set("n", "<leader>|", "<c-w>v", { desc = "Split window vertical" })
vim.keymap.set("n", "<leader>w", "<cmd>w<cr>", { desc = "Save buffer" })
vim.keymap.set("n", "<leader>q", "<cmd>q<cr>", { desc = "Close window" })
vim.keymap.set("n", "<leader>p", '"_dP', { desc = "Paste" })
vim.keymap.set("n", "<leader>y", '"+y', { desc = "Yank" })
vim.keymap.set("v", "<leader>y", '"+y', { desc = "Yank" })
vim.keymap.set("n", "<leader>Y", '"+Y', { desc = "Yank" })
vim.keymap.set("n", "<leader>xL", vim.diagnostic.setloclist, { desc = "Set location list" })
vim.keymap.set("n", "<leader>xl", function()
  vim.cmd(vim.fn.getloclist(0, { winid = 0 }).winid ~= 0 and "lclose" or "lopen")
end, { desc = "Toggle location list" })
vim.keymap.set("n", "<leader>xQ", vim.diagnostic.setqflist, { desc = "Set quickfix list" })
vim.keymap.set("n", "<leader>xq", function()
  vim.cmd(vim.fn.getqflist({ winid = 0 }).winid ~= 0 and "cclose" or "copen")
end, { desc = "Toggle quickfix list" })

vim.keymap.set("x", "<", "<gv")
vim.keymap.set("x", ">", ">gv")

